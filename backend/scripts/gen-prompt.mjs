// Embeds prompts/sahbi.md into src/prompt.generated.ts so serverless bundles
// (e.g. Vercel) never need to read the file at runtime.
// Run: npm run gen:prompt (a test fails if the two drift apart).
import { readFileSync, writeFileSync } from 'node:fs';
import { stdout } from 'node:process';
import { URL } from 'node:url';

const md = readFileSync(new URL('../prompts/sahbi.md', import.meta.url), 'utf8');
const out = `// GENERATED by scripts/gen-prompt.mjs from prompts/sahbi.md — do not edit.\nexport const PROMPT_TEMPLATE = ${JSON.stringify(md)};\n`;
writeFileSync(new URL('../src/prompt.generated.ts', import.meta.url), out);
stdout.write(`prompt.generated.ts: ${md.length} chars\n`);
